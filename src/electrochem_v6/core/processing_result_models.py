"""Normalized result models shared by processing modules."""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any, Mapping


def _json_ready(value: Any) -> Any:
    """Return a plain JSON-compatible value for common scalar types."""
    if value is None:
        return None
    if hasattr(value, "item"):
        try:
            value = value.item()
        except Exception:
            pass
    if isinstance(value, float) and not math.isfinite(value):
        return None
    if isinstance(value, (str, int, float, bool)):
        return value
    if isinstance(value, Mapping):
        return {str(key): _json_ready(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_json_ready(item) for item in value]
    return str(value)


def _clean_text(value: Any) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def _clean_metadata(metadata: Mapping[str, Any] | None) -> dict[str, Any]:
    if not metadata:
        return {}
    return {str(key): _json_ready(value) for key, value in metadata.items()}


@dataclass(frozen=True)
class MetricValue:
    """One named metric generated by a processing step."""

    key: str
    value: Any
    unit: str | None = None
    label: str | None = None
    method: str | None = None
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "key": str(self.key),
            "label": _clean_text(self.label) or str(self.key),
            "value": _json_ready(self.value),
            "unit": _clean_text(self.unit),
            "method": _clean_text(self.method),
            "metadata": _clean_metadata(self.metadata),
        }


@dataclass(frozen=True)
class SourceFileRef:
    """Input file identity for a processing result."""

    sample_name: str
    file_name: str | None = None
    path: str | None = None
    data_type: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "sample_name": str(self.sample_name),
            "file_name": _clean_text(self.file_name),
            "path": _clean_text(self.path),
            "data_type": _clean_text(self.data_type),
        }


@dataclass(frozen=True)
class ProcessingResult:
    """Normalized result for one processed sample/file pair."""

    data_type: str
    sample_name: str
    metrics: tuple[MetricValue, ...] = ()
    source: SourceFileRef | None = None
    artifacts: tuple[str, ...] = ()
    project_id: str | None = None
    run_id: str | None = None
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "data_type": str(self.data_type).upper(),
            "sample_name": str(self.sample_name),
            "source": self.source.to_dict() if self.source else None,
            "metrics": [metric.to_dict() for metric in self.metrics],
            "artifacts": [str(item) for item in self.artifacts if _clean_text(item)],
            "project_id": _clean_text(self.project_id),
            "run_id": _clean_text(self.run_id),
            "metadata": _clean_metadata(self.metadata),
        }

    def metric_map(self) -> dict[str, Any]:
        return {metric.key: _json_ready(metric.value) for metric in self.metrics}


__all__ = ["MetricValue", "ProcessingResult", "SourceFileRef"]
